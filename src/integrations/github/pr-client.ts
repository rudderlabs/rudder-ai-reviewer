/**
 * GitHub PR client for posting comments and annotations
 */

import * as github from '@actions/github';
import * as core from '@actions/core';
import type { SDKDetectionResult } from '../../core/sdk-detector';

export interface PRCommentOptions {
  owner: string;
  repo: string;
  pullNumber: number;
  token: string;
  pathPrefix?: string;
  commitSha?: string;
}

export interface InlineAnnotation {
  path: string;
  line: number;
  message: string;
  annotation_level: 'notice' | 'warning' | 'failure';
}

/**
 * Format SDK detection results as markdown comment
 */
export function formatSDKDetectionComment(
  result: SDKDetectionResult,
  options: { owner: string; repo: string; commitSha: string; pathPrefix?: string }
): string {
  const { installationType, npmVersion, cdnVersion, details, locations } = result;

  let comment = '## 🔍 RudderStack SDK Detection\n\n';

  // Installation type badge
  const badge = {
    npm: '📦 NPM',
    cdn: '🌐 CDN',
    both: '📦🌐 NPM + CDN',
    none: '❌ Not Found',
  }[installationType];

  comment += `**Installation Type:** ${badge}\n\n`;

  // Version information
  if (npmVersion) {
    comment += `**NPM Version:** \`${npmVersion}\`\n`;
  }
  if (cdnVersion) {
    comment += `**CDN Version:** \`${cdnVersion}\`\n`;
  }

  // Details section
  if (details.length > 0) {
    comment += '\n### Details\n\n';
    details.forEach((detail) => {
      comment += `${detail}\n`;
    });
  }

  // Locations section with clickable links
  if (locations.length > 0) {
    comment += '\n### 📍 SDK Usage Locations\n\n';
    locations.forEach((loc, idx) => {
      // Adjust path with prefix if needed
      const fullPath = options.pathPrefix ? `${options.pathPrefix}/${loc.file}` : loc.file;

      // Create GitHub permalink to specific line
      const fileLink = `https://github.com/${options.owner}/${options.repo}/blob/${options.commitSha}/${fullPath}#L${loc.line}`;

      comment += `${idx + 1}. [**${fullPath}:${loc.line}**](${fileLink}) (${loc.type.toUpperCase()})\n`;
      comment += '   ```\n';
      comment += `   ${loc.snippet}\n`;
      comment += '   ```\n\n';
    });
  }

  comment += '\n---\n';
  comment += '_🤖 Generated by [RudderStack PR Reviewer](https://github.com/rudderlabs/pr-reviewer)_\n';

  return comment;
}

/**
 * Post or update PR comment with SDK detection results
 */
export async function postSDKDetectionComment(
  result: SDKDetectionResult,
  options: PRCommentOptions
): Promise<void> {
  const { owner, repo, pullNumber, token, pathPrefix } = options;
  const octokit = github.getOctokit(token);

  try {
    // Get PR to get commit SHA for links
    const { data: pr } = await octokit.rest.pulls.get({
      owner,
      repo,
      pull_number: pullNumber,
    });

    const commitSha = pr.head.sha;

    const commentBody = formatSDKDetectionComment(result, {
      owner,
      repo,
      commitSha,
      pathPrefix,
    });
    const commentIdentifier = '<!-- rudderstack-pr-reviewer-sdk-detection -->';
    const fullCommentBody = `${commentIdentifier}\n${commentBody}`;

    // Find existing comment
    const { data: comments } = await octokit.rest.issues.listComments({
      owner,
      repo,
      issue_number: pullNumber,
    });

    const existingComment = comments.find((comment) =>
      comment.body?.includes(commentIdentifier)
    );

    if (existingComment) {
      // Update existing comment
      core.info(`Updating existing comment #${existingComment.id}`);
      await octokit.rest.issues.updateComment({
        owner,
        repo,
        comment_id: existingComment.id,
        body: fullCommentBody,
      });
    } else {
      // Create new comment
      core.info('Creating new PR comment');
      await octokit.rest.issues.createComment({
        owner,
        repo,
        issue_number: pullNumber,
        body: fullCommentBody,
      });
    }

    core.info('✅ Successfully posted SDK detection comment');
  } catch (error) {
    const errorMessage = error instanceof Error ? error.message : String(error);
    core.warning(`Failed to post PR comment: ${errorMessage}`);
    throw error;
  }
}

/**
 * Post inline review comments to PR files (only for changed files)
 */
export async function postInlineAnnotations(
  annotations: InlineAnnotation[],
  options: PRCommentOptions
): Promise<void> {
  if (annotations.length === 0) {
    core.info('No inline annotations to post');
    return;
  }

  const { owner, repo, pullNumber, token } = options;
  const octokit = github.getOctokit(token);

  try {
    // Get PR files to see what's actually in the diff
    const { data: prFiles } = await octokit.rest.pulls.listFiles({
      owner,
      repo,
      pull_number: pullNumber,
    });

    const changedFiles = new Set(prFiles.map((f) => f.filename));

    core.info(`Changed files in PR: ${Array.from(changedFiles).join(', ')}`);
    core.info(`SDK locations to annotate: ${annotations.map(a => a.path).join(', ')}`);

    // Filter annotations to only include files that are in the PR diff
    const annotationsInDiff = annotations.filter((ann) => changedFiles.has(ann.path));

    if (annotationsInDiff.length === 0) {
      core.info('No SDK locations in changed files (see main comment for all locations)');
      return;
    }

    // Get the PR to get commit SHA
    const { data: pr } = await octokit.rest.pulls.get({
      owner,
      repo,
      pull_number: pullNumber,
    });

    const commitSha = pr.head.sha;

    const commentIdentifier = '<!-- rudderstack-sdk-location -->';

    // Get existing review comments created by us to avoid duplicates
    const { data: existingComments } = await octokit.rest.pulls.listReviewComments({
      owner,
      repo,
      pull_number: pullNumber,
    });

    const ourExistingComments = existingComments.filter((comment) =>
      comment.body?.includes(commentIdentifier)
    );

    core.info(`Found ${ourExistingComments.length} existing SDK location comment(s)`);

    // Filter out annotations that already have comments (avoid duplicates)
    const existingCommentLocations = new Set(
      ourExistingComments.map((c) => `${c.path}:${c.line}`)
    );

    const newAnnotations = annotationsInDiff.filter(
      (ann) => !existingCommentLocations.has(`${ann.path}:${ann.line}`)
    );

    if (newAnnotations.length === 0) {
      core.info('All locations already have comments');
      return;
    }

    // Create review comments for each new location
    let successCount = 0;
    for (const ann of newAnnotations) {
      try {
        await octokit.rest.pulls.createReviewComment({
          owner,
          repo,
          pull_number: pullNumber,
          body: `${commentIdentifier}\n${ann.message}`,
          commit_id: commitSha,
          path: ann.path,
          line: ann.line,
        });
        successCount++;
      } catch (error) {
        const errorMessage = error instanceof Error ? error.message : String(error);
        core.debug(`Could not post inline comment on ${ann.path}:${ann.line}: ${errorMessage}`);
        // Continue with other annotations
      }
    }

    if (successCount > 0) {
      core.info(`✅ Posted ${successCount} new inline comment(s) on changed files`);
    }
  } catch (error) {
    const errorMessage = error instanceof Error ? error.message : String(error);
    core.warning(`Failed to post inline annotations: ${errorMessage}`);
    // Don't throw - inline annotations are nice-to-have
  }
}
